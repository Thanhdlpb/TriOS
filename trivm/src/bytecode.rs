use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum OpCode {
    Push(f64),
    Pop,
    Dup,
    Swap,
    Load(String),
    Store(String),
    Jmp(usize),
    Jz(usize),
    Jnz(usize),
    Call(usize),
    Ret,
    Add,
    Sub,
    Mul,
    Div,
    Mod,
    Eq,
    Neq,
    Gt,
    Lt,
    Gte,
    Lte,
    And,
    Or,
    Not,
    Print,
    PrintLn,
    Input,
    AssertFact(String, String, String),
    QueryFact(String, String, String),
    Halt,
    Nop,
}
